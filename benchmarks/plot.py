"""Plot grouped raw transform timings with a linear millisecond scale per operation.

The default figure reproduces the historical single-host summary. Pass --csv
to replace those observations with results generated by benchmark.py.
"""

from __future__ import annotations

import argparse
import csv
import math
from html import escape
from pathlib import Path

# Historical medians in milliseconds: 512x256 Gaussian, float32, one thread.
SNAPSHOT = {
    "scalar_analysis": {
        "PySpharm": 28.545004,
        "pyspharm-cpp": 1.113594,
        "ducc0": 1.105053,
    },
    "wind_analysis": {
        "PySpharm": 20.102418,
        "pyspharm-cpp": 2.863599,
        "ducc0": 2.690205,
    },
    "multi_field_analysis": {
        "PySpharm": 225.173798,
        "pyspharm-cpp": 9.432003,
        "ducc0": 9.130268,
    },
}
OPERATIONS = (
    ("scalar_analysis", "Scalar analysis"),
    ("wind_analysis", "Wind analysis"),
    ("multi_field_analysis", "Eight-field scalar analysis"),
)
BACKENDS = (
    ("PySpharm", "PySpharm 1.0.9", "#975463"),
    ("pyspharm-cpp", "pyspharm-cpp", "#3077a3"),
    ("ducc0", "DUCC 0.42.0", "#4c876b"),
)


def load_csv(path: Path) -> dict[str, dict[str, float]]:
    """Extract matching medians for all nine bars from benchmark.py output."""
    measurements: dict[str, dict[str, float]] = {name: {} for name, _ in OPERATIONS}
    with path.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            operation = row["operation"]
            if operation not in measurements:
                continue
            if (
                row["nlon"] != "512"
                or row["nlat"] != "256"
                or row["dtype"] != "float32"
                or row["threads"] != "1"
                or int(row["nfields"]) != (8 if operation == "multi_field_analysis" else 1)
                or row["backend"] not in dict((key, label) for key, label, _ in BACKENDS)
            ):
                continue
            measurements[operation][row["backend"]] = float(row["median_ms"])
    for operation, title in OPERATIONS:
        for backend, _, _ in BACKENDS:
            value = measurements[operation].get(backend)
            if value is None or not math.isfinite(value) or value <= 0:
                raise ValueError(
                    f"Missing positive timing: {title}, {backend}. "
                    "Install both reference packages for all nine bars."
                )
    return measurements


def axis_maximum(values: dict[str, float]) -> int:
    """Select a readable linear axis that begins at zero."""
    observed = max(values.values()) * 1.05
    step = 5 if observed <= 30 else 25 if observed <= 250 else 100
    return max(step, math.ceil(observed / step) * step)


def render_svg(measurements: dict[str, dict[str, float]]) -> str:
    """Render three groups of three raw timings, each on a linear ms axis."""
    left, span = 222, 490
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="900" height="705" '
        'viewBox="0 0 900 705" role="img" aria-labelledby="chart-title chart-desc">',
        '<title id="chart-title">Measured spherical harmonic transform latencies</title>',
        '<desc id="chart-desc">Three groups show PySpharm, pyspharm-cpp and '
        'DUCC latencies in milliseconds. Each group uses its own linear axis '
        'starting at zero; axes should not be compared by bar length across groups.</desc>',
        '<rect width="900" height="705" fill="white"/>',
        '<text x="26" y="37" font-family="sans-serif" font-size="21" '
        'font-weight="600" fill="#1c3040">Measured SHT latency</text>',
        '<text x="26" y="62" font-family="sans-serif" font-size="13" '
        'fill="#536578">512×256 Gaussian · float32 · one thread · lower is better</text>',
    ]
    for index, (operation, label) in enumerate(OPERATIONS):
        top = 88 + index * 192
        values = measurements[operation]
        maximum = axis_maximum(values)
        lines.append(
            f'<text x="26" y="{top + 16}" font-family="sans-serif" '
            f'font-size="16" font-weight="600" fill="#1c3040">{escape(label)}</text>'
        )
        for j, (backend, backend_label, color) in enumerate(BACKENDS):
            y = top + 34 + 34 * j
            value = values[backend]
            width = value / maximum * span
            lines.extend(
                [
                    f'<text x="26" y="{y + 17}" font-family="sans-serif" '
                    f'font-size="13" fill="#273849">{escape(backend_label)}</text>',
                    f'<rect x="{left}" y="{y}" width="{width:.1f}" height="23" '
                    f'rx="2" fill="{color}"/>',
                    f'<text x="{left + width + 8:.1f}" y="{y + 17}" '
                    'font-family="sans-serif" font-size="13" fill="#273849">'
                    f'{value:.3f} ms</text>',
                ]
            )
        axis_y = top + 147
        for fraction in (0, 0.5, 1):
            x = left + fraction * span
            lines.extend(
                [
                    f'<line x1="{x:.1f}" y1="{axis_y - 4}" x2="{x:.1f}" '
                    f'y2="{axis_y}" stroke="#8fa1af"/>',
                    f'<text x="{x:.1f}" y="{axis_y + 16}" '
                    'text-anchor="middle" font-family="sans-serif" '
                    'font-size="11" fill="#536578">'
                    f'{maximum * fraction:g}</text>',
                ]
            )
        lines.append(
            f'<line x1="{left}" y1="{axis_y}" x2="{left + span}" '
            f'y2="{axis_y}" stroke="#8fa1af"/>'
        )
    lines.extend(
        [
            '<text x="26" y="688" font-family="sans-serif" font-size="12" '
            'fill="#536578">Independent linear millisecond scale for each operation; '
            'historical single-host medians.</text>',
            "</svg>",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, help="CSV generated by benchmark.py")
    parser.add_argument(
        "--output", type=Path, default=Path(__file__).with_name("timings.svg")
    )
    args = parser.parse_args()
    values = load_csv(args.csv) if args.csv else SNAPSHOT
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_svg(values), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
